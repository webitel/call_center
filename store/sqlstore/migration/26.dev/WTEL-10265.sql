create table if not exists call_center.cc_skill_group
(
    id          bigint generated by default as identity
        constraint cc_skill_group_pk primary key,
    domain_id   bigint      not null
        constraint cc_skill_group_domain_fk references directory.wbt_domain (dc) on delete cascade,
    name        varchar     not null,
    description varchar     default ''::character varying not null,
    created_at  timestamptz,
    created_by  bigint
        constraint cc_skill_group_created_by_fk references directory.wbt_user (id) on delete set null,
    updated_at  timestamptz,
    updated_by  bigint
        constraint cc_skill_group_updated_by_fk references directory.wbt_user (id) on delete set null
);

create index if not exists cc_skill_group_domain_id_name_index
    on call_center.cc_skill_group (domain_id, name);

create unique index if not exists cc_skill_group_domain_id_udx
    on call_center.cc_skill_group (id, domain_id);

create table if not exists call_center.cc_skill_group_acl
(
    id      bigint generated by default as identity
        constraint cc_skill_group_acl_pk primary key,
    dc      bigint   not null
        constraint cc_skill_group_acl_domain_fk references directory.wbt_domain (dc) on delete cascade,
    grantor bigint
        constraint cc_skill_group_acl_grantor_id_fk references directory.wbt_auth (id) on delete set null,
    object  bigint   not null,
    subject bigint   not null,
    access  smallint default 0 not null,
    constraint cc_skill_group_acl_object_fk
        foreign key (object, dc) references call_center.cc_skill_group (id, domain_id) on delete cascade,
    constraint cc_skill_group_acl_grantor_fk
        foreign key (grantor, dc) references directory.wbt_auth (id, dc) on update cascade on delete cascade,
    constraint cc_skill_group_acl_subject_fk
        foreign key (subject, dc) references directory.wbt_auth (id, dc) on delete cascade
);

create index if not exists cc_skill_group_acl_grantor_idx
    on call_center.cc_skill_group_acl (grantor);
create unique index if not exists cc_skill_group_acl_object_subject_udx
    on call_center.cc_skill_group_acl (object, subject) include (access);
create unique index if not exists cc_skill_group_acl_subject_object_udx
    on call_center.cc_skill_group_acl (subject, object) include (access);

drop trigger if exists cc_skill_group_set_rbac_acl on call_center.cc_skill_group;
create trigger cc_skill_group_set_rbac_acl
    after insert on call_center.cc_skill_group
    for each row
execute function call_center.tg_obj_default_rbac('cc_skill_group');

