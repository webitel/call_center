    on call_center.cc_skill_in_agent (skill_group_id) where skill_group_id is not null;

create or replace view call_center.cc_skill_group_view as
select g.id,
       g.created_at,
       call_center.cc_get_lookup(c.id, coalesce(c.name, c.username::text)::varchar) as created_by,
       g.updated_at,
       call_center.cc_get_lookup(u.id, coalesce(u.name, u.username::text)::varchar) as updated_by,
       g.name,
       g.description,
       g.domain_id,
       coalesce(sk.skills, '[]'::jsonb)                                             as skills,
       coalesce(agents.total_agents, 0)                                            as total_agents,
       coalesce(agents.active_agents, 0)                                           as active_agents
from call_center.cc_skill_group g
         left join directory.wbt_user c on c.id = g.created_by
         left join directory.wbt_user u on u.id = g.updated_by
         left join lateral ( select jsonb_agg(call_center.cc_get_lookup(s.id::bigint, s.name) order by s.name) as skills
                             from call_center.cc_skill_in_group sig
                                      join call_center.cc_skill s on s.id = sig.skill_id
                             where sig.skill_group_id = g.id ) sk on true
         left join lateral ( select count(distinct aig.agent_id)                            as total_agents,
                                    count(distinct sia.agent_id) filter (where sia.enabled) as active_agents
                             from call_center.cc_agent_in_skill_group aig
                                      left join call_center.cc_skill_in_group sig on sig.skill_group_id = g.id
                                      left join call_center.cc_skill_in_agent sia
                                                on sia.agent_id = aig.agent_id and sia.skill_id = sig.skill_id
                             where aig.skill_group_id = g.id ) agents on true;

create or replace function call_center.cc_skill_group_reconcile_agent(p_agent_id integer)
    returns void
    language plpgsql
as
$$
declare
    v_now bigint := (extract(epoch from now()) * 1000)::bigint;
begin

    insert into call_center.cc_skill_in_agent (skill_id, agent_id, capacity, enabled, skill_group_id,
                                               created_at, updated_at)
    select gr.skill_id, p_agent_id, gr.capacity, true, gr.skill_group_id, v_now, v_now
    from (
             select sig.skill_id,
                    max(sig.capacity)::smallint as capacity,
                    min(g.id)                   as skill_group_id
             from call_center.cc_agent a
                      join call_center.cc_agent_in_skill_group aig on aig.agent_id = a.id
                      join call_center.cc_skill_group g on g.id = aig.skill_group_id and g.domain_id = a.domain_id
                      join call_center.cc_skill_in_group sig on sig.skill_group_id = g.id
             where a.id = p_agent_id
             group by sig.skill_id
         ) gr
    where not exists (select 1
                      from call_center.cc_skill_in_agent d
                      where d.agent_id = p_agent_id
                        and d.skill_id = gr.skill_id
                        and d.skill_group_id is null)
    on conflict (agent_id, skill_id) do update
        set capacity       = excluded.capacity,
            skill_group_id = excluded.skill_group_id,
            updated_at     = excluded.updated_at
        where call_center.cc_skill_in_agent.skill_group_id is not null;

    delete
    from call_center.cc_skill_in_agent sia
    where sia.agent_id = p_agent_id
      and sia.skill_group_id is not null
      and not exists (select 1
                      from call_center.cc_agent_in_skill_group aig
                               join call_center.cc_skill_in_group sig on sig.skill_group_id = aig.skill_group_id
                      where aig.agent_id = p_agent_id
                        and sig.skill_id = sia.skill_id);
end;
$$;

create or replace function call_center.cc_skill_group_reconcile_group(p_group_id bigint)
    returns void
    language plpgsql
as
$$
declare
    r record;
begin
    for r in select agent_id from call_center.cc_agent_in_skill_group where skill_group_id = p_group_id
        loop
            perform call_center.cc_skill_group_reconcile_agent(r.agent_id);
        end loop;
end;
$$;
